import { config } from '../config.js';
import { store } from './store.js';

/**
 * Normalizes Dify or Local Engine results to the target contract specified in Section 5.4:
 * {
 *   success: true,
 *   data: {
 *     projectSummary: string,
 *     requiredSkills: string[],
 *     recommendedRoles: string[],
 *     matches: [
 *       { studentId, name, skills, availability, matchScore, reasons }
 *     ],
 *     meta: { source, isLiveDify, note }
 *   }
 * }
 */
export async function matchTeam({ projectIdea, requiredSkills = [], preferredRoles = [], availability = 'Flexible' }) {
  // If Dify API key is present and configured, execute the upstream Dify Workflow
  if (config.dify.isConfigured) {
    try {
      const difyResult = await executeDifyWorkflow({
        projectIdea,
        requiredSkills,
        preferredRoles,
        availability,
      });
      return {
        success: true,
        data: {
          ...difyResult,
          meta: {
            source: 'dify_workflow',
            isLiveDify: true,
            note: 'Generated by live Dify PEERCRAFT workflow.',
          },
        },
      };
    } catch (difyError) {
      console.warn('[DifyService] Upstream Dify execution failed:', difyError.message);
      // As per Section 5.5, if a fallback mechanism is used, it must be explicitly designed and labeled.
      const localResult = executeDeterministicMatch({
        projectIdea,
        requiredSkills,
        preferredRoles,
        availability,
      });
      return {
        success: true,
        data: {
          ...localResult,
          meta: {
            source: 'deterministic_local_engine',
            isLiveDify: false,
            upstreamError: difyError.message,
            note: 'Upstream Dify call failed. Fallback to PeerCraft Deterministic Engine using verified student profiles.',
          },
        },
      };
    }
  }

  // When Dify credentials are not provided in environment, use the deterministic scoring engine
  const localResult = executeDeterministicMatch({
    projectIdea,
    requiredSkills,
    preferredRoles,
    availability,
  });

  return {
    success: true,
    data: {
      ...localResult,
      meta: {
        source: 'deterministic_local_engine',
        isLiveDify: false,
        note: 'Calculated by PeerCraft Deterministic Matching Engine using stored student profiles. Configure DIFY_API_KEY in server/.env to enable live Dify PEERCRAFT workflow.',
      },
    },
  };
}

/**
 * Invokes the Dify Workflow API
 */
async function executeDifyWorkflow({ projectIdea, requiredSkills, preferredRoles, availability }) {
  const url = `${config.dify.baseUrl}/v1/workflows/run`;
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 20000); // 20s server-side timeout

  const payload = {
    inputs: {
      project_idea: projectIdea,
      required_skills: Array.isArray(requiredSkills) ? requiredSkills.join(', ') : requiredSkills,
      preferred_roles: Array.isArray(preferredRoles) ? preferredRoles.join(', ') : preferredRoles,
      availability: availability || 'Flexible',
    },
    response_mode: 'blocking',
    user: 'peercraft-student',
  };

  try {
    const res = await fetch(url, {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${config.dify.apiKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(payload),
      signal: controller.signal,
    });

    clearTimeout(timeoutId);

    if (!res.ok) {
      const errorText = await res.text().catch(() => '');
      throw new Error(`Dify HTTP ${res.status}: ${errorText || res.statusText}`);
    }

    const json = await res.json();
    return parseDifyWorkflowOutput(json, projectIdea, requiredSkills);
  } catch (err) {
    clearTimeout(timeoutId);
    if (err.name === 'AbortError') {
      throw new Error('Dify request timed out after 20 seconds');
    }
    throw err;
  }
}

/**
 * Parses upstream Dify workflow JSON response safely
 */
function parseDifyWorkflowOutput(json, fallbackIdea, fallbackSkills) {
  const outputs = json?.data?.outputs || json?.outputs || {};

  let projectSummary = outputs.project_summary || outputs.projectSummary || '';
  let requiredSkills = outputs.required_skills || outputs.requiredSkills || fallbackSkills || [];
  let recommendedRoles = outputs.recommended_roles || outputs.recommendedRoles || [];
  let rawMatches = outputs.matches || outputs.candidates || [];

  if (typeof requiredSkills === 'string') {
    requiredSkills = requiredSkills.split(',').map((s) => s.trim()).filter(Boolean);
  }
  if (typeof recommendedRoles === 'string') {
    recommendedRoles = recommendedRoles.split(',').map((s) => s.trim()).filter(Boolean);
  }

  // Parse raw matches
  const matches = (Array.isArray(rawMatches) ? rawMatches : []).map((m, idx) => ({
    studentId: m.studentId || m.student_id || `match-${idx + 1}`,
    name: m.name || m.studentName || 'Student Candidate',
    skills: Array.isArray(m.skills) ? m.skills : (m.skills ? [m.skills] : []),
    availability: m.availability || 'Flexible',
    matchScore: typeof m.matchScore === 'number' ? m.matchScore : (m.score || 85),
    reasons: Array.isArray(m.reasons) ? m.reasons : (m.reason ? [m.reason] : ['Matched by Dify PEERCRAFT workflow.']),
  }));

  return {
    projectSummary: projectSummary || `Analysis for: "${fallbackIdea.substring(0, 100)}..."`,
    requiredSkills,
    recommendedRoles,
    matches,
  };
}

/**
 * Transparent, deterministic local matching engine across stored student profiles
 * Calculates scores based on verified skill overlap, role fit, and availability.
 */
function executeDeterministicMatch({ projectIdea, requiredSkills = [], preferredRoles = [], availability = 'Flexible' }) {
  const students = store.getStudents();
  const normalizedPrefRoles = preferredRoles.map((r) => r.trim().toLowerCase()).filter(Boolean);

  // Derive suggested skills from idea keywords if none provided
  const derivedSkills = [...requiredSkills];
  const ideaLower = projectIdea.toLowerCase();
  const skillKeywords = ['react', 'node.js', 'python', 'pytorch', 'figma', 'docker', 'kubernetes', 'flutter', 'fastapi', 'typescript', 'postgresql'];
  skillKeywords.forEach((kw) => {
    if (ideaLower.includes(kw) && !derivedSkills.some((s) => s.toLowerCase() === kw)) {
      derivedSkills.push(kw.charAt(0).toUpperCase() + kw.slice(1));
    }
  });

  const rankedCandidates = students.map((student) => {
    let score = 30; // base compatibility
    const reasons = [];

    // 1. Skill overlap (up to 40 points)
    const studentSkillsLower = student.skills.map((s) => s.toLowerCase());
    const matchedSkills = derivedSkills.filter((req) =>
      studentSkillsLower.some((ss) => ss.includes(req.toLowerCase()) || req.toLowerCase().includes(ss))
    );

    if (matchedSkills.length > 0) {
      const skillScore = Math.min(40, matchedSkills.length * 15);
      score += skillScore;
      reasons.push(`Direct skill alignment in: ${matchedSkills.join(', ')}`);
    }

    // 2. Role alignment (up to 20 points)
    const studentRolesLower = (student.preferredRoles || []).map((r) => r.toLowerCase());
    const matchedRoles = normalizedPrefRoles.filter((pref) =>
      studentRolesLower.some((sr) => sr.includes(pref) || pref.includes(sr))
    );
    if (matchedRoles.length > 0) {
      score += 20;
      reasons.push(`Target role fit: ${student.preferredRoles.join(', ')}`);
    }

    // 3. Availability and reputation bonus (up to 10 points)
    if (student.reputationScore >= 4.8) {
      score += 5;
      reasons.push(`High verified peer reputation (${student.reputationScore}/5.0 with ${student.collaborationsCompleted} completed projects)`);
    }

    if (student.availability.toLowerCase().includes('flexible') ||
        (availability && student.availability.toLowerCase().includes(availability.toLowerCase()))) {
      score += 5;
      reasons.push(`Availability matches schedule (${student.availability})`);
    }

    const finalScore = Math.min(98, Math.max(45, score));

    return {
      studentId: student.id,
      name: student.name,
      avatar: student.avatar,
      major: student.major,
      year: student.year,
      skills: student.skills,
      availability: student.availability,
      matchScore: finalScore,
      reasons: reasons.length > 0 ? reasons : ['General campus profile alignment'],
      github: student.github,
      portfolio: student.portfolio,
      reputationScore: student.reputationScore,
    };
  });

  // Sort descending by matchScore
  rankedCandidates.sort((a, b) => b.matchScore - a.matchScore);

  // Auto-generate project summary
  const summary = `Evaluated project scope "${projectIdea.substring(0, 80)}${projectIdea.length > 80 ? '...' : ''}". Identified ${derivedSkills.length} key competencies with emphasis on ${derivedSkills.slice(0, 3).join(', ') || 'general engineering'}.`;

  const recommendedRoles = preferredRoles.length > 0
    ? preferredRoles
    : ['Frontend Developer', 'Backend Architect', 'UI/UX Designer'];

  return {
    projectSummary: summary,
    requiredSkills: derivedSkills,
    recommendedRoles,
    matches: rankedCandidates.slice(0, 4), // top 4 ranked matches
  };
}
